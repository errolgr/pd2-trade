/** Expands a compact spec into the full token set; shared defaults (status colors, quality, radius) fill the rest. */
export function defineTheme(s: ThemeSpec): Theme {
  const dark = s.mode === 'dark';
  const vars: Record<ThemeToken, string> = {
    background: s.background,
    foreground: s.foreground,
    card: s.card,
    'card-foreground': s.foreground,
    popover: s.popover,
    'popover-foreground': s.foreground,
    primary: s.primary,
    'primary-foreground': s.primaryForeground,
    secondary: s.secondary,
    'secondary-foreground': s.foreground,
    muted: s.muted,
    'muted-foreground': s.mutedForeground,
    accent: s.accent,
    'accent-foreground': s.accentForeground,
    destructive: s.destructive,
    'destructive-foreground': 'oklch(0.985 0 0)',
    border: s.border,
    input: s.input,
    ring: s.ring,
    'chart-1': s.charts[0],
    'chart-2': s.charts[1],
    'chart-3': s.charts[2],
    'chart-4': s.charts[3],
    'chart-5': s.charts[4],
    sidebar: s.popover,
    'sidebar-foreground': s.foreground,
    'sidebar-primary': s.primary,
    'sidebar-primary-foreground': s.primaryForeground,
    'sidebar-accent': s.accent,
    'sidebar-accent-foreground': s.accentForeground,
    'sidebar-border': s.border,
    'sidebar-ring': s.ring,
    success: dark ? PALETTE.green500 : PALETTE.green700,
    'success-foreground': dark ? PALETTE.darkInk : PALETTE.lightInk,
    warning: dark ? PALETTE.amber400 : PALETTE.amber700,
    'warning-foreground': dark ? PALETTE.darkInk : PALETTE.lightInk,
    info: dark ? PALETTE.sky400 : PALETTE.sky700,
    'info-foreground': dark ? PALETTE.darkInk : PALETTE.lightInk,
    surface: atWindowOpacity(s.background),
    'surface-foreground': s.foreground,
    'surface-elevated': atWindowOpacity(s.popover, 'elevated'),
    glow: s.glow,
    scrim: dark ? 'oklch(0 0 0 / 0.6)' : 'oklch(0.206 0.018 264.052 / 0.35)',
    ...(dark ? DARK_QUALITY : { ...LIGHT_QUALITY, 'q-normal': s.foreground }),
    ...s.quality,
    radius: '0.5rem',
    ...s.overrides,
  };
  return {
    id: s.id,
    name: s.name,
    mode: s.mode,
    description: s.description,
    swatch: [s.background, s.primary, s.glow],
    vars,
  };
}

