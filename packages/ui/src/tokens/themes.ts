/**
 * Theme registry: 21 color themes (11 dark, 10 light).
 *
 * Every theme defines the full per-theme token set listed in `THEME_TOKENS`. Colors are oklch (alpha allowed);
 * `color-mix()`/`var()` expressions stay as written. The app applies a theme at runtime (src/lib/themes.ts in the
 * overlay), and the generated `tailwind.css` ships the default theme's values in `:root` for first paint.
 */

import { PALETTE, type QualityToken, type Theme, type ThemeMode, type ThemeToken } from './tokens';

/** Compact theme input for `defineTheme`; `quality`/`overrides` replace the derived defaults. */
export interface ThemeSpec {
  id: string;
  name: string;
  mode: ThemeMode;
  description: string;
  background: string;
  foreground: string;
  card: string;
  popover: string;
  primary: string;
  primaryForeground: string;
  secondary: string;
  muted: string;
  mutedForeground: string;
  accent: string;
  accentForeground: string;
  destructive: string;
  border: string;
  input: string;
  ring: string;
  glow: string;
  charts: [string, string, string, string, string];
  quality?: Partial<Record<QualityToken, string>>;
  overrides?: Partial<Record<ThemeToken, string>>;
}

/**
 * `color` at the window opacity chosen in Settings → Interface → Window transparency. Panels use
 * `--window-opacity`; popovers, tooltips and toasts (`elevated`) use the gentler `--window-opacity-elevated`
 * so text floating over a see-through panel stays readable. Both are set by `applyWindowTransparency`.
 */
export const atWindowOpacity = (color: string, layer: 'panel' | 'elevated' = 'panel') =>
  `color-mix(in oklab, ${color} var(${layer === 'elevated' ? '--window-opacity-elevated' : '--window-opacity'}), transparent)`;

