/**
 * Generates `generated/tailwind.css` from the token source in `src/tokens`: the default theme's values in `:root`
 * (first paint before `applyTheme` runs), the global scales, and the Tailwind 4 `@theme` mapping for every token.
 *
 * Run: `npm run build:css` (root or this package). The overlay's vite.config.ts also calls `writeTailwindCss()`
 * on every dev/build start (token edits restart the dev server), and `build-css.test.ts` fails when the committed
 * file is stale.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import {
  DEFAULT_THEME_ID,
  DURATION_MS,
  EASING,
  getTheme,
  RADIUS_SCALE,
  SHADOWS,
  SHAPE_TOKENS,
  THEME_TOKENS,
  TRACKING,
  TYPE_SCALE,
  WIDTHS,
  Z_LAYERS,
  type ColorToken,
} from '../src/tokens';

export const TAILWIND_CSS_PATH = fileURLToPath(new URL('../generated/tailwind.css', import.meta.url));

const INDENT = '    ';
const block = (comment: string, selector: string, decls: string[]) =>
  `/* ${comment} */\n${selector} {\n${decls.map((d) => (d ? INDENT + d : d)).join('\n')}\n}`;
const cubicBezier = (points: readonly number[]) => `cubic-bezier(${points.join(', ')})`;
const radiusStep = (offsetPx: number) =>
  offsetPx === 0 ? 'var(--radius)' : `calc(var(--radius) ${offsetPx < 0 ? '-' : '+'} ${Math.abs(offsetPx)}px)`;

const COLOR_TOKENS = THEME_TOKENS.filter((t): t is ColorToken => !(SHAPE_TOKENS as readonly string[]).includes(t));

export function renderTailwindCss(): string {
  const theme = getTheme(DEFAULT_THEME_ID);

  return `${[
    '/*\n * GENERATED by packages/ui/scripts/build-css.ts from packages/ui/src/tokens. Do not edit by hand:\n * change the token source and run `npm run build:css` (vite dev/build regenerate it too).\n */',
    block(
      `Per-theme tokens. The app's applyTheme writes the active theme inline on <html>; these are the\n * \`${theme.id}\` values so first paint is correct without JS.`,
      ':root',
      [
        ...THEME_TOKENS.map((t) => `--${t}: ${theme.vars[t]};`),
        '/* Window transparency (Settings → Interface): applyWindowTransparency sets both; opaque by default. */',
        '--window-opacity: 100%;',
        '--window-opacity-elevated: 100%;',
        '',
        `color-scheme: ${theme.mode};`,
      ],
    ),
    block('Global scales (not per theme).', ':root', [
      `--ease-out: ${cubicBezier(EASING.out)};`,
      `--ease-spring: ${cubicBezier(EASING.spring)};`,
      ...Object.entries(DURATION_MS).map(([k, ms]) => `--dur-${k}: ${ms}ms;`),
    ]),
    block('Literal values (not var()) to avoid self-referencing the same-named :root vars.', '@theme', [
      `--ease-out: ${cubicBezier(EASING.out)};`,
      `--ease-spring: ${cubicBezier(EASING.spring)};`,
      '',
      ...Object.entries(Z_LAYERS).map(([k, z]) => `--z-index-${k}: ${z};`),
      '',
      '/* Type scale: only the named steps exist (Tailwind defaults reset). */',
      '--text-*: initial;',
      ...Object.entries(TYPE_SCALE).flatMap(([k, [size, lineHeight, letterSpacing]]) => [
        `--text-${k}: ${size};`,
        `--text-${k}--line-height: ${lineHeight};`,
        ...(letterSpacing ? [`--text-${k}--letter-spacing: ${letterSpacing};`] : []),
      ]),
      '',
      '/* Disclosure motion (Accordion, Collapsible): height follows the Radix content-height var. */',
      `--animate-accordion-down: accordion-down ${DURATION_MS.med}ms ${cubicBezier(EASING.out)};`,
      `--animate-accordion-up: accordion-up ${DURATION_MS.fast}ms ${cubicBezier(EASING.out)};`,
      `--animate-collapsible-down: collapsible-down ${DURATION_MS.med}ms ${cubicBezier(EASING.out)};`,
      `--animate-collapsible-up: collapsible-up ${DURATION_MS.fast}ms ${cubicBezier(EASING.out)};`,
      ...(['accordion', 'collapsible'] as const).flatMap((kind) => [
        `@keyframes ${kind}-down { from { height: 0; } to { height: var(--radix-${kind}-content-height); } }`,
        `@keyframes ${kind}-up { from { height: var(--radix-${kind}-content-height); } to { height: 0; } }`,
      ]),
      '',
      ...Object.entries(TRACKING).map(([k, v]) => `--tracking-${k}: ${v};`),
      '',
      ...Object.entries(WIDTHS).map(([k, v]) => `--container-${k}: ${v};`),
    ]),
    block(
      'Inline: per-theme values resolve where used, so themed subtrees (picker previews) get their own vars.',
      '@theme inline',
      [
        ...COLOR_TOKENS.map((t) => `--color-${t}: var(--${t});`),
        '',
        ...Object.entries(RADIUS_SCALE).map(([k, offset]) => `--radius-${k}: ${radiusStep(offset)};`),
        '',
        ...Object.entries(SHADOWS).map(([k, v]) => `--shadow-${k}: ${v};`),
      ],
    ),
  ].join('\n\n')}\n`;
}

/** Writes the generated CSS when it differs from the file on disk; returns whether it changed. */
export function writeTailwindCss(): boolean {
  const next = renderTailwindCss();
  let current: string | undefined;
  try {
    current = readFileSync(TAILWIND_CSS_PATH, 'utf8');
  } catch {
    current = undefined;
  }
  if (current === next) return false;
  mkdirSync(dirname(TAILWIND_CSS_PATH), { recursive: true });
  writeFileSync(TAILWIND_CSS_PATH, next);
  return true;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const changed = writeTailwindCss();
  console.log(`${changed ? 'wrote' : 'up to date:'} ${TAILWIND_CSS_PATH}`);
}
